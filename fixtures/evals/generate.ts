/** Every E case of guardrails section 7, in the table's order. */
export const EVAL_FIXTURES: readonly EvalCaseFixtures[] = [
  G1_1,
  G1_6,
  G1_11,
  G3_1,
  G3_2,
  G3_5,
  G3_8,
  G6_3,
  G8_1,
  G8_2,
  G8_3,
  G8_5,
  G8_6,
  G8_9,
  G11_1,
  G11_4,
  G11_5,
  G12_2,
  G14_1,
  G14_2,
];

/** The path of a case's fixture file, from the repository root. */
export function fixturePath(id: string, file: EvalFixtureFile): string {
  return `fixtures/evals/${id}/${file.file}`;
}

/** A fixture file's bytes: a comment naming what it is, then the content as YAML. */
export function renderFixture(id: string, file: EvalFixtureFile): string {
  const header = [
    `# TEST fixture: synthetic input of the guardrail eval ${id} (evals/guardrails/${id}.yaml).`,
    '# Generated by fixtures/evals/generate.ts from its source.ts; not an owner document (rule 13).',
  ].join('\n');
  return `${header}\n${stringify(file.content, { lineWidth: 0 })}`;
}

function main(argv: readonly string[]): void {
  const at = argv.indexOf('--out');
  const out = at < 0 ? undefined : argv[at + 1];
  if (out === undefined) throw new Error('usage: tsx fixtures/evals/generate.ts --out <folder>');
  for (const evalCase of EVAL_FIXTURES) {
    const folder = join(out, 'fixtures', 'evals', evalCase.id);
    mkdirSync(folder, { recursive: true });
    for (const file of evalCase.files) writeFileSync(join(folder, file.file), renderFixture(evalCase.id, file));
  }
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
