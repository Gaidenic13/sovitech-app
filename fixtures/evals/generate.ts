/**
 * Generator of the guardrail evals' synthetic fixtures (guardrails section 7, "Model-
 * behaviour evals": "Each holds a synthetic fixture, a task, and assertions on the
 * structured output"; prompt 3 section 8, "Fixtures"; rule 13, "Fixtures are synthetic").
 *
 *   tsx fixtures/evals/generate.ts --out <folder>
 *
 * writes each case's files to <folder>/fixtures/evals/<ID>/<name>.yaml; `--out .` from the
 * repository root rewrites the committed files. The fixture-manifest check runs it into a
 * temporary folder and compares the bytes with fixtures/manifest.json, and the eval runner
 * sends a fixture only when the manifest lists it with those bytes
 * (packages/ai/src/evals/fixtures.ts).
 *
 * The content of each case is in fixtures/evals/<ID>/source.ts (see ./format.ts for why).
 * The case files that use these fixtures are evals/guardrails/<ID>.yaml.
 */
