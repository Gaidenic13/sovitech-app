export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id)
}

// Split "TSHK621F001, TSHK642F001" into individual article codes
export function articleCodes(p: Product): string[] {
  return (p.modelCodes ?? "").split(/[,;]\s*/).map((c) => c.trim()).filter(Boolean)
}

