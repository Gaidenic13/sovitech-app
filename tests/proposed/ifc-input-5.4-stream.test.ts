describe('IFC-1 · R-027 · F-IFC-04 · ADR 0034 (gated: ifc-values; waits for ifc-input 6.2.1, 6.2.2, 6.2.3, 6.2.10): the per-line form reads back to the job\'s own section', { timeout: 120_000 }, () => {
  it.each(MODELS)('IFC-1 · F-IFC-04: %s: the worker\'s line-by-line reading gives the in-memory output, and its section opens to the same facts and proposals', async (model) => {
    const source = all.get(model);
    if (source === undefined) throw new Error(`${model} was written`);
    const gates = openGates();
    const read = await readJobOutput(source.path, source.request, gates);
    if (!read.ok) throw new Error(`refused: ${read.code} ${JSON.stringify(read.problems)}`);
    const inMemory = parseExtractionOutput(parse(JSON.stringify(source.inMemory), { schema: 'json' }) as unknown);
    if (!inMemory.ok) throw new Error('the in-memory output is valid');
    const { ifcValues: streamedSection, ...streamed } = read.output;
    const { ifcValues: inMemorySection, ...rest } = inMemory.value;
    expect(streamed).toEqual(rest);
    const opened = openIfcValues(streamedSection, gates);
    expect(opened.open).toBe(true);
    expect(opened).toEqual(openIfcValues(inMemorySection, gates));
    if (!opened.open) return;
    expect(opened.facts.length).toBeGreaterThan(0);
    expect(read.lines).toBe(readFileSync(source.path, 'utf8').split('\n').length - 1);
  });
});

describe('F-INGEST-04 · R-027 · ADR 0034 (gated: ifc-values): a line refused refuses the whole output, with a named code', { timeout: 120_000 }, () => {
  async function refusal(path: string, limits?: Parameters<typeof readJobOutput>[3]): Promise<{ readonly code: string; readonly problems: readonly string[] }> {
    const read = await readJobOutput(path, revA.request, openGates(), limits);
    if (read.ok) throw new Error('the output was accepted');
    return { code: read.code, problems: read.problems.map((problem) => problem.code) };
  }

  it('F-INGEST-04: a file cut inside a line is output_truncated; cut at a line end, or right after the output, ifc_values_truncated', async () => {
    const text = readFileSync(revA.path, 'utf8');
    expect(await refusal(edited(revA, () => text.slice(0, text.length - 20)))).toMatchObject({ code: 'output_truncated' });
    expect(await refusal(edited(revA, (lines) => lines.slice(0, -1)))).toEqual({ code: 'ifc_values_truncated', problems: ['stream:truncated'] });
    expect(await refusal(edited(revA, (lines) => lines.slice(0, 1)))).toEqual({ code: 'ifc_values_truncated', problems: ['stream:header'] });
    expect(await refusal(edited(revA, (lines) => lines[0] ?? ''))).toEqual({ code: 'ifc_values_truncated', problems: ['stream:header'] });
  });

  it('F-INGEST-04: a line past the bound is output_line_too_long (1 MiB, and any bound the reader is given)', async () => {
    const long = `{"statement":{"stepId":1,"text":"#1=${'X'.repeat(IFC_VALUES_LINE_MAX_BYTES)}"}}`;
    expect(await refusal(edited(revA, (lines) => [lines[0] ?? '', lines[1] ?? '', long, ...lines.slice(2)]))).toMatchObject({ code: 'output_line_too_long' });
    expect(await refusal(revA.path, { outputBytes: 4 * 1024 * 1024, lineBytes: 64, gatedBytes: 512 * 1024 * 1024 })).toMatchObject({ code: 'output_line_too_long' });
  });

  it('F-INGEST-04: a line that is not JSON is output_line_malformed', async () => {
    expect(await refusal(edited(revA, (lines) => lines.map((line, index) => (index === firstOf(lines, 'fact') ? line.slice(0, -3) : line))))).toMatchObject({ code: 'output_line_malformed' });
  });

  it('F-INGEST-04 · IFC-1: a line the contract refuses is ifc_values_invalid, with the problem\'s code and never its text', async () => {
    const withExcerpt = await refusal(edited(revA, (lines) => lines.map((line, index) => (index === firstOf(lines, 'fact') ? line.replace('{"fact":{', '{"fact":{"excerpt":"TEST",') : line))));
    expect(withExcerpt).toEqual({ code: 'ifc_values_invalid', problems: ['unknown_key'] });
    const unknownStatement = await refusal(edited(revA, (lines) => lines.map((line, index) => (index === firstOf(lines, 'fact') ? line.replace(/"stepIds":\[[0-9]+\]/u, '"stepIds":[999999999]') : line))));
    expect(unknownStatement).toEqual({ code: 'ifc_values_invalid', problems: ['stream:unknown_statement'] });
    const notItsOwn = await refusal(edited(revA, (lines) => lines.map((line, index) => (index === firstOf(lines, 'statement') ? line.replace(/"text":"#[0-9]+=/u, '"text":"#7=') : line))));
    expect(notItsOwn).toEqual({ code: 'ifc_values_invalid', problems: ['stream:statement'] });
    const unknownFact = await refusal(edited(revA, (lines) => lines.map((line, index) => (index === firstOf(lines, 'proposal') ? line.replace(/"evidenceFactIds":\["[^"]+"/u, '"evidenceFactIds":["f-not-written"') : line))));
    expect(unknownFact.code).toBe('ifc_values_invalid');
    expect(unknownFact.problems).toContain('invariant:ifc_proposals');
  });

  it('F-INGEST-04: lines out of order, a statement no fact quotes, a line too many, or a section where the output may carry none are refused', async () => {
    const order = await refusal(
      edited(revA, (lines) => {
        const fact = firstOf(lines, 'fact');
        const moved = [...lines];
        const [line] = moved.splice(fact, 1);
        moved.splice(fact - 1, 0, line ?? '');
        return moved;
      }),
    );
    expect(order).toEqual({ code: 'ifc_values_invalid', problems: ['stream:order'] });
    const unquoted = await refusal(
      edited(revA, (lines) => {
        const header = parse(lines[1] ?? '', { schema: 'json' }) as { ifcValuesStream: { statements: number } };
        header.ifcValuesStream.statements += 1;
        const fact = firstOf(lines, 'fact');
        return [lines[0] ?? '', JSON.stringify(header), ...lines.slice(2, fact), '{"statement":{"stepId":999999998,"text":"#999999998=IFCTEST();"}}', ...lines.slice(fact)];
      }),
    );
    expect(unquoted).toEqual({ code: 'ifc_values_invalid', problems: ['stream:unquoted_statement'] });
    expect(await refusal(edited(revA, (lines) => [...lines, lines.at(-1) ?? '']))).toEqual({ code: 'ifc_values_excess', problems: ['stream:excess'] });
    const absent = await refusal(edited(revA, (lines) => [lines[0] ?? '', (lines[1] ?? '').replace('"present"', '"absent"'), ...lines.slice(2)]));
    expect(absent).toEqual({ code: 'ifc_values_invalid', problems: ['stream:section'] });
    const noRecord = await refusal(
      edited(revA, (lines) => {
        const output = parse(lines[0] ?? '', { schema: 'json' }) as Record<string, unknown>;
        delete output['ifcModel'];
        return [JSON.stringify(output), ...lines.slice(1)];
      }),
    );
    expect(noRecord).toEqual({ code: 'ifc_values_invalid', problems: ['invariant:format_sections'] });
  });
});

/** The reader's command line in a process of its own, as in its sandbox (its image gives V8 a 2 GB heap), timed; its output kept at `keep`. */
class ReaderProcessRunner implements ExtractorRunner {
  readonly runs: { readonly status: number | null; readonly seconds: number; readonly maxRssKb?: number }[] = [];
  private readonly script = join(WORK, 'reader-child.mts');

  constructor(private readonly keep?: string) {
    writeFileSync(
      this.script,
      [
        'const [cli, ...args] = process.argv.slice(2);',
        'const { main } = await import(cli);',
        'const status = await main(args, () => undefined);',
        'process.stdout.write(JSON.stringify({ status, maxRssKb: process.resourceUsage().maxRSS }));',
        'process.exitCode = status;',
      ].join('\n'),
    );
  }

  run(job: SandboxJob): Promise<SandboxOutcome> {
    if (job.reader !== 'ifc-reader') return Promise.resolve({ outcome: 'failed', code: 'extractor_failed' });
    const started = Date.now();
    const args = ['--request', job.requestPath, '--document', job.inputPath, '--out', job.outputDirectory, ...(job.idsPath === undefined ? [] : ['--ids', job.idsPath])];
    const child = spawn(process.execPath, ['--max-old-space-size=2048', '--import', 'tsx', this.script, join(REPO_ROOT, 'packages/ifc-reader/src/cli.ts'), ...args], { cwd: REPO_ROOT, stdio: ['ignore', 'pipe', 'ignore'] });
    const chunks: Buffer[] = [];
    child.stdout.on('data', (chunk: Buffer) => chunks.push(chunk));
    return new Promise((resolve) => {
      child.on('exit', (status) => {
        const report = (() => {
          try {
            return parse(Buffer.concat(chunks).toString('utf8'), { schema: 'json' }) as { maxRssKb?: number };
          } catch {
            return {};
          }
        })();
        this.runs.push({ status, seconds: (Date.now() - started) / 1000, ...(report.maxRssKb === undefined ? {} : { maxRssKb: report.maxRssKb }) });
        if (status === 0 && this.keep !== undefined) {
          // The worker removes its folder after the step: a link (or a copy) keeps the file for a measurement of the reading alone.
          try {
            linkSync(join(job.outputDirectory, 'output.json'), this.keep);
          } catch {
            copyFileSync(join(job.outputDirectory, 'output.json'), this.keep);
          }
        }
        resolve(status === 0 ? { outcome: 'finished' } : { outcome: 'failed', code: 'extractor_failed' });
      });
    });
  }
}

/** A runner that writes a fixed file as the job's output (a tampered copy of a real one). */
class FileRunner implements ExtractorRunner {
  constructor(private readonly path: string) {}
  run(job: SandboxJob): Promise<SandboxOutcome> {
    mkdirSync(job.outputDirectory, { recursive: true });
    writeFileSync(join(job.outputDirectory, 'output.json'), readFileSync(this.path));
    return Promise.resolve({ outcome: 'finished' });
  }
}

describe('F-INGEST-04 · F-IFC-03 · ADR 0034 (gated: ifc-values; waits for ifc-input 6.2.1, 6.2.2, 6.2.3, 6.2.10): through the worker', () => {
  let api: TestApi;
  const perfHash = existsSync(PERF) ? contentHashOf(readFileSync(PERF)) : undefined;

  beforeAll(async () => {
    const fixtures = fixtureUploadGuard(REPO_ROOT);
    // The perf model is the perf profile's output, never in the manifest: this suite's guard takes its hash too.
    api = await startTestApi({ readModels: true, uploadGuard: { accepts: (hash) => fixtures.accepts(hash) || hash === perfHash } });
  }, 300_000);

  afterAll(async () => {
    await api.stop();
  });

  function worker(runner: ExtractorRunner): AnalysisWorker {
    return new AnalysisWorker({ store: api.services.store, files: api.files, log: api.services.log }, runner, {
      workerId: 'test-stream-worker',
      serviceId: api.extractionAccountId,
      gates: openGates(),
      ...(api.services.modelReading === undefined ? {} : { modelReading: api.services.modelReading }),
      maxAttempts: 1,
      retryAfterSeconds: 0,
      staleAfterSeconds: 3600,
    });
  }

  async function uploaded(label: string, fileName: string, bytes: Buffer): Promise<{ readonly projectId: string; readonly documentId: string }> {
    const { ownerId, projectId } = await ownerWithProject(api, label);
    const auth = await signIn(api, ownerId);
    const result = await upload(api, auth, projectId, fileName, bytes, 8 * 1024 * 1024);
    const documentId = result.body.documentId;
    if (documentId === undefined) throw new Error(`the upload answered ${String(result.status)} ${String(result.body.code)}`);
    return { projectId, documentId };
  }

  it('F-INGEST-04: a malformed line in a model\'s output fails the job with output_line_malformed, and nothing of the output is stored', { timeout: 300_000 }, async () => {
    const { projectId, documentId } = await uploaded('proposed stream, malformed line', 'demo-hotel-mep-rev-a.ifc', readFileSync(join(REPO_ROOT, 'fixtures/ifc/demo-hotel-mep-rev-a.ifc')));
    const bad = edited(revA, (lines) =>
      lines.map((line, index) => {
        if (index === 0) {
          const output = parse(line, { schema: 'json' }) as { job: Record<string, string> };
          output.job['projectId'] = projectId;
          output.job['documentId'] = documentId;
          return JSON.stringify(output);
        }
        return index === firstOf(lines, 'fact') + 3 ? '{"fact": not json' : line;
      }),
    );
    const stored = (): Promise<unknown> =>
      withRequest(api.database.app, { userId: api.extractionAccountId, projectId }, async (request) => ({
        records: await readModelRecords(request, documentId),
        texts: await readDocumentTexts(request, revA.request.job.contentHash, ''),
        elements: await readIfcElements(request, documentId),
      }));
    const before = await stored();
    // Before the job: only what the upload registered (the file's name), no model record, no IFC text, no element.
    expect(before).toMatchObject({ records: [], elements: [] });
    const steps = await worker(new FileRunner(bad)).drain();
    expect(steps.map((step) => (step.kind === 'failed' || step.kind === 'retry' ? step.code : step.kind))).toEqual(['output_line_malformed']);
    expect(await stored()).toEqual(before);
  });

  it.runIf(perfHash !== undefined)('F-INGEST-04 · F-IFC-03: the perf model, refused as output.too_large before, runs through the reader, the worker\'s line-by-line reading and the gated value path', { timeout: 1_800_000 }, async () => {
    const bytes = readFileSync(PERF);
    const uploadStarted = Date.now();
    const { projectId, documentId } = await uploaded('proposed stream, perf model', 'demo-hotel-perf.ifc', bytes);
    const uploadSeconds = (Date.now() - uploadStarted) / 1000;
    const kept = join(WORK, 'perf-output.json');
    const runner = new ReaderProcessRunner(kept);
    const started = Date.now();
    const steps = await worker(runner).drain();
    const stepSeconds = (Date.now() - started) / 1000;
    expect(steps.map((step) => step.kind)).toEqual(['done']);
    expect(runner.runs).toHaveLength(1);
    const counts = await withRequest(api.database.app, { userId: api.extractionAccountId, projectId }, async (request) => {
      const elements = await readIfcElements(request, documentId);
      const kinds = ['building', 'storey', 'space', 'zone', 'element'] as const;
      return {
        records: (await readModelRecords(request, documentId)).length,
        statements: (await readDocumentTexts(request, contentHashOf(bytes), 'ifc:step:')).length,
        byKind: Object.fromEntries(kinds.map((kind) => [kind, elements.filter((element) => element.kind === kind).length])),
      };
    });
    // The quoted statements are stored as the model's text; the building, its 186 storeys and 22,264 spaces are registered.
    expect(counts.records).toBe(1);
    expect(counts.statements).toBeGreaterThan(200_000);
    expect(counts.byKind).toMatchObject({ building: 1, storey: 186, space: 22_264 });
    // The worker's reading alone, on the same file: line by line, into the sealed section.
    const rssBefore = process.memoryUsage().rss;
    const readStarted = Date.now();
    const read = await readJobOutput(kept, { contractVersion: '1.0.0', job: { projectId, documentId, contentHash: contentHashOf(bytes) }, declaredFormat: 'ifc', ifcValues: true, datasets: [], derivatives: [], limits: EXTRACTION_LIMITS }, openGates());
    const readSeconds = (Date.now() - readStarted) / 1000;
    const rssAfterRead = process.memoryUsage().rss;
    expect(read).toMatchObject({ ok: true });
    const reader = runner.runs[0];
    const report = {
      model: { bytes: bytes.length },
      uploadSeconds,
      readerProcess: { seconds: reader?.seconds, peakRssMB: reader?.maxRssKb === undefined ? undefined : Math.round((reader.maxRssKb * 1024) / 1e6) },
      workerStepSeconds: stepSeconds,
      workerStepWithoutReaderSeconds: reader === undefined ? undefined : Math.round((stepSeconds - reader.seconds) * 10) / 10,
      readingAlone: { seconds: readSeconds, lines: read.ok ? read.lines : undefined, bytes: read.bytesRead, rssGrowthMB: Math.round((rssAfterRead - rssBefore) / 1e6) },
      thisProcessPeakRssMB: Math.round((process.resourceUsage().maxRSS * 1024) / 1e6),
      stored: counts,
    };
    process.stdout.write(`ADR 0034 perf measurement: ${JSON.stringify(report)}\n`);
  });
});
