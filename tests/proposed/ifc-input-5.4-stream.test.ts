/**
 * Proposed behaviour, not indexed (prompt 3 sections 5.4, 8 and 10, phase 2;
 * docs/adr/0034-streamed-ifc-output-and-sandbox-bounds.md): the per-line form of the sealed IFC
 * section, written by the IFC reader's command line and read line by line by the API's worker,
 * with `ifc-values` (and, for the proposals, the gates of their mechanisms) opened by the
 * test-utils override. It waits for what the value path waits for: ifc-input 6.2.1, 6.2.2, 6.2.3
 * and 6.2.10 (the `ifc-values` gate), the approved IFC mapping tables and the owner's revision of
 * build-readiness decision 4.
 *
 * - The round trip: for each of the four fixture models, the lines the command line writes read
 *   back, through the worker's reading (apps/api/src/jobs/output-file.ts), to the same output and
 *   the same opened section as the job's in-memory output.
 * - The refusals: a line cut short, too long, not JSON, refused by the contract, out of order,
 *   missing or one too many refuses the whole output, with a named code.
 * - The worker: a refused line stores nothing of the output; and the `perf` model (git-ignored,
 *   generated by the fixtures' perf profile: 101 MB, 1,457,649 instances, 157,166 elements),
 *   whose section was refused as `output.too_large` before, runs through the whole path with the
 *   gate open: the reader's command line in its own process (as in its sandbox, with its 2 GB
 *   V8 heap), the worker's line-by-line reading, and the gated value path's storing (ADR 0033).
 *   Its times and peak memory are printed for ADR 0034.
 *
 * Every account, project, field and table is TEST data; the models are the generated synthetic
 * fixtures (fixtures/ifc/), and the perf model is the perf profile's output (never in the
 * manifest; this suite's upload guard takes its hash besides the manifest's).
 *
 * Ids: ifc-input 5.4 IFC-1 (the locator each fact carries); R-027 (sealed); F-INGEST-04 (the
 * worker), F-IFC-03 and F-IFC-04 (gated).
 */
