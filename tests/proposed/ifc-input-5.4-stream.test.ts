const JOB_PROJECT = '0192f0a0-0000-7000-8000-00000000c501';

interface Written {
  readonly path: string;
  readonly request: ExtractionRequest;
  readonly inMemory: ExtractionOutput;
}

/** The reader's command line on a model, IFC values asked for with the TEST table mounted, and the same job in memory. */
async function written(model: string, label: string): Promise<Written> {
  const bytes = readFileSync(join(REPO_ROOT, 'fixtures/ifc', `${model}.ifc`));
  const folder = join(WORK, label);
  mkdirSync(join(folder, 'datasets'), { recursive: true });
  mkdirSync(join(folder, 'out'), { recursive: true });
  writeFileSync(join(folder, 'datasets', `${DATASET.id}@${DATASET.version}.json`), JSON.stringify({ ...DATASET, kind: 'ifc-mapping', rules: TEST_RULES }));
  const request = checkedRequest({
    contractVersion: '1.0.0',
    job: { projectId: JOB_PROJECT, documentId: '0192f0a0-0000-7000-8000-00000000c502', contentHash: contentHashOf(bytes) },
    declaredFormat: 'ifc',
    ifcValues: true,
    datasets: [DATASET],
    derivatives: [],
    limits: EXTRACTION_LIMITS,
  });
  writeFileSync(join(folder, 'request.json'), JSON.stringify(request));
  const status = await readIfc(
    ['--request', join(folder, 'request.json'), '--document', join(REPO_ROOT, 'fixtures/ifc', `${model}.ifc`), '--out', join(folder, 'out'), '--datasets', join(folder, 'datasets')],
    () => undefined,
  );
  if (status !== 0) throw new Error(`the reader's command line exited ${String(status)}`);
  const inMemory = await runIfcJob(request, bytes, { datasets: join(folder, 'datasets') });
  return { path: join(folder, 'out', 'output.json'), request, inMemory };
}

/** A copy of an output file's lines, changed by `edit`, written beside it. */
let copies = 0;
function edited(source: Written, edit: (lines: string[]) => string[] | string): string {
  const text = readFileSync(source.path, 'utf8');
  const lines = text.slice(0, -1).split('\n');
  const changed = edit(lines);
  copies += 1;
  const path = join(WORK, `edited-${String(copies)}.json`);
  writeFileSync(path, typeof changed === 'string' ? changed : `${changed.join('\n')}\n`);
  return path;
}

/** The line index of the first line of a kind (0 is the output). */
function firstOf(lines: readonly string[], kind: 'statement' | 'fact' | 'proposal'): number {
  const index = lines.findIndex((line) => line.startsWith(`{"${kind}":`));
  if (index < 0) throw new Error(`no ${kind} line`);
  return index;
}

